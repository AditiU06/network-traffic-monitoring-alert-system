"""Component-level tests for PipelineCoordinator."""
import os
import tempfile
import time
import unittest
from pathlib import Path

# Ensure paths
_workspace_root = Path(__file__).resolve().parent.parent.parent
_backend_root = _workspace_root / "E3_E4_Backend" / "backend"
_e2_root = _workspace_root / "E2_Threat_Detection"
_contracts_root = _workspace_root / "Integration" / "Contracts"

import sys
for p in (_workspace_root, _backend_root, _e2_root, _contracts_root):
    if p.exists() and str(p) not in sys.path:
        sys.path.insert(0, str(p))

from app.engines.e3_data_management.service import DataManagementService
from Integration.Orchestration.coordinator import PipelineCoordinator


class TestPipelineCoordinator(unittest.TestCase):
    def setUp(self):
        self.temp_dir = tempfile.mkdtemp()
        self.db_path = os.path.join(self.temp_dir, "test_coordinator.db")
        self.svc = DataManagementService(self.db_path)
        self.admin_id = self.svc.create_user("System Admin", "admin", "admin@kletech.ac.in", "pw")

        # Create a sample Zeek log with 40 rejected connections to trigger R01 Address Scan / Port Scan
        self.log_path = Path(self.temp_dir) / "sample_traffic.log"
        lines = [
            "#separator \\x09",
            "#fields\tts\tuid\tid.orig_h\tid.orig_p\tid.resp_h\tid.resp_p\tproto\tservice\tduration\torig_bytes\tresp_bytes\tconn_state\thistory\torig_pkts\tresp_pkts",
        ]
        t0 = int(time.time()) - 1000
        for i in range(40):
            lines.append(f"{t0 + i}\tC{i:04d}\t192.168.1.100\t{50000 + i}\t10.0.0.{i+1}\t443\ttcp\t-\t0.01\t100\t0\tREJ\tSr\t1\t1")
        self.log_path.write_text("\n".join(lines) + "\n", encoding="utf-8")

        self.now_iso = time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime())

    def test_full_pipeline_coordination_benchmark_mode(self):
        coordinator = PipelineCoordinator(self.svc)
        run_id = "RUN_COORD_001"

        # Create initial run record as E4 would
        self.svc.save_processing_run({
            "run_id": run_id,
            "initiated_by": self.admin_id,
            "file_name": self.log_path.name,
            "log_type": "conn",
            "run_mode": "BENCHMARK",
            "started_at": self.now_iso,
            "status": "RUNNING",
        })

        # Execute synchronous pipeline coordination
        result = coordinator.execute_pipeline(run_id, self.log_path, mode="BENCHMARK", threads=4)

        self.assertEqual(result["status"], "COMPLETED")
        self.assertEqual(result["valid_count"], 40)
        self.assertGreaterEqual(result["alerts_generated"], 1)

        # Verify run status in E3
        run = self.svc.get_run(run_id)
        self.assertEqual(run["status"], "COMPLETED")
        self.assertEqual(run["valid_count"], 40)

        # Verify events stored in E3 with preserved fields (uid, history, total_bytes)
        # Note: search_events returns items ordered by event_timestamp DESC
        events_resp = self.svc.search_events(run_id=run_id, size=50)
        self.assertEqual(events_resp["total"], 40)
        latest_event = events_resp["items"][0]
        oldest_event = events_resp["items"][-1]
        self.assertEqual(latest_event["source_ip"], "192.168.1.100")
        self.assertEqual(latest_event["uid"], "C0039")
        self.assertEqual(oldest_event["uid"], "C0000")
        self.assertEqual(oldest_event["history"], "Sr")
        self.assertEqual(oldest_event["total_bytes"], 100)
        self.assertEqual(oldest_event["total_packets"], 2)

        # Verify benchmark metrics stored in E3
        perf_resp = self.svc.get_performance_results(run_id)
        self.assertEqual(len(perf_resp["metrics"]), 2)
        self.assertIsNotNone(perf_resp["comparison"])
        self.assertEqual(perf_resp["comparison"]["equivalence_status"], "PASS")

        # Verify alerts generated by E2 and saved in E3
        alerts_resp = self.svc.search_alerts(run_id=run_id)
        self.assertGreaterEqual(alerts_resp["total"], 1)
        rule_codes = [a["rule_code"] for a in alerts_resp["items"]]
        self.assertIn("R07", rule_codes)  # From preserved 'history' containing 'r'
        self.assertIn("R01", rule_codes)  # From > 25 failed connections to unique IPs

        # Verify all events marked evaluated
        unevaluated = self.svc.get_events_for_detection(run_id)
        self.assertEqual(len(unevaluated), 0)

    def test_pipeline_failure_handling(self):
        coordinator = PipelineCoordinator(self.svc)
        run_id = "RUN_COORD_FAIL"
        non_existent_log = Path(self.temp_dir) / "does_not_exist.log"

        self.svc.save_processing_run({
            "run_id": run_id,
            "initiated_by": self.admin_id,
            "file_name": "does_not_exist.log",
            "log_type": "conn",
            "run_mode": "MULTITHREADED",
            "started_at": self.now_iso,
            "status": "RUNNING",
        })

        with self.assertRaises(Exception):
            coordinator.execute_pipeline(run_id, non_existent_log, mode="MULTITHREADED", threads=4)

        # Verify run marked FAILED
        run = self.svc.get_run(run_id)
        self.assertEqual(run["status"], "FAILED")

    def test_pipeline_repeated_run_idempotency(self):
        """Verifies repeated runs do not duplicate events or alerts."""
        coordinator = PipelineCoordinator(self.svc)
        run_id = "RUN_IDEMPOTENT_001"

        self.svc.save_processing_run({
            "run_id": run_id,
            "initiated_by": self.admin_id,
            "file_name": self.log_path.name,
            "log_type": "conn",
            "run_mode": "MULTITHREADED",
            "started_at": self.now_iso,
            "status": "RUNNING",
        })

        # Run 1
        res1 = coordinator.execute_pipeline(run_id, self.log_path, mode="MULTITHREADED", threads=4)
        self.assertEqual(res1["status"], "COMPLETED")
        self.assertEqual(res1["valid_count"], 40)
        alerts_count_1 = self.svc.search_alerts(run_id=run_id)["total"]

        # Run 2 on the same run_id (re-submission / retry)
        # Should gracefully recognize all 40 events are already stored and not insert duplicates
        res2 = coordinator.execute_pipeline(run_id, self.log_path, mode="MULTITHREADED", threads=4)
        self.assertEqual(res2["status"], "COMPLETED")
        self.assertEqual(res2["valid_count"], 0)  # 0 new events inserted
        self.assertEqual(res2["malformed_count"], 40)  # 40 recognized as 'already stored'

        # Total stored events remain exactly 40
        events_total = self.svc.search_events(run_id=run_id)["total"]
        self.assertEqual(events_total, 40)

        # No duplicate alerts stored
        alerts_count_2 = self.svc.search_alerts(run_id=run_id)["total"]
        self.assertEqual(alerts_count_1, alerts_count_2)


if __name__ == "__main__":
    unittest.main()
